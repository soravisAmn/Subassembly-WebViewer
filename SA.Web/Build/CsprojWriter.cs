// Round 7: the .csproj for one DLL and one Civil 3D version. Same settings as tests-civil3d/build/Round6.csproj
// (x64, EnableDynamicLoading, WinForms + WPF, no default compile items). The .cs files are compiled where they are:
// the build never copies or edits them. Autodesk DLLs are referenced in place (Private=false: never copied to the output).

using System.Security;
using System.Text;

namespace SA.Build;

public static class CsprojWriter
{
    // (reference name, path inside the Civil 3D install)
    public static readonly (string Name, string Path)[] References =
    {
        ("acdbmgd", "acdbmgd.dll"),
        ("accoremgd", "accoremgd.dll"),
        ("acmgd", "acmgd.dll"),
        ("AecBaseMgd", @"ACA\AecBaseMgd.dll"),
        ("AeccDbMgd", @"C3D\AeccDbMgd.dll"),
    };

    // Source package (M4): the .csproj sits next to the .cs files, the DLL goes next to it (and the .atc). build.bat passes
    // C3DInstall and TargetFramework; the defaults below are for building it by hand.
    public static string GeneratePortable(string dllName, string tfm, IEnumerable<string> fileNames)
    {
        var text = Generate(dllName, tfm, @"C:\Program Files\Autodesk\AutoCAD " + (tfm.StartsWith("net10") ? "2027" : "2026"), fileNames.Select(f => @"C:\x\" + f), @"C:\x");
        text = text.Replace("<OutputPath>C:\\x\\</OutputPath>", "<OutputPath>$(MSBuildProjectDirectory)\\</OutputPath>")
                   .Replace($"<TargetFramework>{tfm}</TargetFramework>", $"<TargetFramework Condition=\"'$(TargetFramework)' == ''\">{tfm}</TargetFramework>");
        foreach (var f in fileNames) text = text.Replace($"Include=\"{SecurityElement.Escape(@"C:\x\" + f)}\"", $"Include=\"{SecurityElement.Escape(f)}\"");
        return text.Replace("Generated by SA Drawing Studio (Build). Rebuilt on every build: do not edit.", "SA Drawing Studio source package. Build with build.bat (finds Civil 3D, sets C3DInstall and TargetFramework).");
    }

    // outDir: where the DLL goes. c3dInstall: default for the C3DInstall property (can be overridden: -p:C3DInstall=...)
    public static string Generate(string dllName, string tfm, string c3dInstall, IEnumerable<string> files, string outDir)
    {
        string X(string s) => SecurityElement.Escape(s) ?? "";
        string Dir(string d) => d.TrimEnd('\\', '/') + "\\";
        var sb = new StringBuilder();
        sb.Append("<Project Sdk=\"Microsoft.NET.Sdk\">\r\n\r\n");
        sb.Append("  <!-- Generated by SA Drawing Studio (Build). Rebuilt on every build: do not edit. -->\r\n");
        sb.Append("  <PropertyGroup>\r\n");
        sb.Append($"    <TargetFramework>{X(tfm)}</TargetFramework>\r\n");
        sb.Append($"    <AssemblyName>{X(dllName)}</AssemblyName>\r\n");
        sb.Append("    <Nullable>disable</Nullable>\r\n");
        sb.Append("    <UseWindowsForms>true</UseWindowsForms>\r\n");
        sb.Append("    <UseWPF>true</UseWPF>\r\n");
        sb.Append("    <EnableDynamicLoading>true</EnableDynamicLoading>\r\n");
        sb.Append("    <ImplicitUsings>disable</ImplicitUsings>\r\n");
        sb.Append("    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\r\n");
        sb.Append("    <GenerateDocumentationFile>false</GenerateDocumentationFile>\r\n");
        sb.Append("    <PlatformTarget>x64</PlatformTarget>\r\n");
        sb.Append("    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>\r\n");
        sb.Append($"    <OutputPath>{X(Dir(outDir))}</OutputPath>\r\n");
        sb.Append($"    <C3DInstall Condition=\"'$(C3DInstall)' == ''\">{X(Dir(c3dInstall))}</C3DInstall>\r\n");
        sb.Append("  </PropertyGroup>\r\n\r\n");
        sb.Append("  <ItemGroup>\r\n");
        foreach (var f in files) sb.Append($"    <Compile Include=\"{X(Path.GetFullPath(f))}\" />\r\n");
        sb.Append("  </ItemGroup>\r\n\r\n");
        sb.Append("  <ItemGroup>\r\n");
        foreach (var (name, path) in References)
            sb.Append($"    <Reference Include=\"{name}\"><HintPath>$(C3DInstall){path}</HintPath><Private>false</Private></Reference>\r\n");
        sb.Append("  </ItemGroup>\r\n\r\n");
        sb.Append("</Project>\r\n");
        return sb.ToString();
    }
}
